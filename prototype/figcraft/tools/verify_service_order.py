def click(label,target,device):
    before=preview();source=before['name'];edge=next(e for e in m['edges'] if e['source']==source and e['label']==label)
    node=api.ask('node.get',{'id':edge['node'],'depth':0})
    y=node['y'];p=preview()
    api.ask('ui.set',{'presentScroll':[0,min(p['scrollRange'][1],max(0,y-p['frameSize'][1]*.4))]});time.sleep(.07)
    p=preview();hot=next((h for h in p['hotspots'] if h['id']==edge['node']),None)
    assert hot,('Missing hotspot',label,p)
    r=hot['rect'];point=[(r[0]+r[2])/2,(r[1]+r[3])/2]
    for event in ({'move':point},{'down':point},{'up':point}):api.ask('ui.input',{'events':[event]});time.sleep(.035)
    time.sleep(.05);after=preview()
    assert after and after['name']==device+'-so-'+target,(source,label,target,after)
    results.append({'source':source,'label':label,'target':after['name'],'node':edge['node'],'passed':True})
    if len(results)%20==0:
        (ROOT/'evidence/service-order-playback.json').write_text(json.dumps(results,indent=2))
        print(json.dumps({'serviceOrderStepsPassed':len(results)}),flush=True)
